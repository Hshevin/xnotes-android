package com.xnotes.format.interop

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * W2-1 contract (docs/movinkpad/process/ipados-wave2-contracts-2026-11-24.md, "W2-1"): note and canvas
 * bundles written by the Android app decode identically on every platform, and a save without edits keeps
 * every entry's content.
 *
 * Fixtures live in shared/src/commonTest/fixtures/interop/. Each `<name>.xnote` / `<name>.xcanvas` was written
 * by the pre-migration Android codec (commit a07e803e) and sits next to `<name>.summary.txt`, the
 * [BundleSummary.canonical] text recorded on the JVM at the same time. Fixtures are never regenerated by the
 * migrated codec: they are Android's real output, and that is the point of the test.
 */
class BundleInteropTest {

    @Test
    fun theFixtureSetCoversEveryKindOfBundle() {
        val names = interopFixtureNames()
        val required = listOf(
            "note-ink-text-pages",   // paged note: strokes, flow text, permanent page ids
            "note-pdf-annotated",    // note carrying an embedded PDF and markups
            "note-layers",           // several drawing layers on one page
            "canvas-ink-image",      // infinite canvas: strokes, an image, connectors
            "canvas-mind-map",       // canvas with a mind map entry (raised format version)
        )
        for (r in required) assertTrue(names.any { it.startsWith("$r.") }, "missing fixture $r")
    }

    @Test
    fun androidBundlesDecodeToTheRecordedSummary() {
        for (name in bundleNames()) {
            val expected = interopFixture(summaryOf(name)).decodeToString().trimEnd()
            val actual = BundleInterop.summarize(name, interopFixture(name)).canonical().trimEnd()
            assertEquals(expected, actual, name)
        }
    }

    @Test
    fun aSaveWithoutEditsKeepsIdentityAndEveryEntrysContent() {
        for (name in bundleNames()) {
            val original = interopFixture(name)
            val before = BundleInterop.summarize(name, original)
            val resaved = BundleInterop.reencode(name, original)
            val after = BundleInterop.summarize(name, resaved)

            assertEquals(before.documentId, after.documentId, name)
            assertEquals(before.pageIds, after.pageIds, name)
            assertEquals(before.inkDigest, after.inkDigest, "$name: stroke samples must not be re-encoded")
            assertEquals(before.entryNames, after.entryNames, name)
            for (entry in before.entryNames) {
                if (entry in BundleInterop.VOLATILE_ENTRIES) continue
                assertEquals(before.entryContentCrc[entry], after.entryContentCrc[entry], "$name: entry $entry changed")
            }
        }
    }

    @Test
    fun volatileEntriesAreFewAndNamed() {
        // Only bookkeeping that legitimately changes on every save (e.g. a modified time) may differ.
        assertTrue(BundleInterop.VOLATILE_ENTRIES.size <= 2, BundleInterop.VOLATILE_ENTRIES.toString())
    }

    @Test
    fun aResavedBundleIsReadableAgainOnTheSamePlatform() {
        for (name in bundleNames()) {
            val once = BundleInterop.reencode(name, interopFixture(name))
            val twice = BundleInterop.reencode(name, once)
            assertEquals(
                BundleInterop.summarize(name, once).canonical(),
                BundleInterop.summarize(name, twice).canonical(),
                name,
            )
        }
    }

    private fun bundleNames() = interopFixtureNames().filter { it.endsWith(".xnote") || it.endsWith(".xcanvas") }.sorted()

    private fun summaryOf(bundle: String) = bundle.substringBeforeLast('.') + ".summary.txt"
}

/** File names in shared/src/commonTest/fixtures/interop/. Provided per platform in the test source sets. */
expect fun interopFixtureNames(): List<String>

/** Bytes of one fixture file. Provided per platform in the test source sets. */
expect fun interopFixture(name: String): ByteArray
